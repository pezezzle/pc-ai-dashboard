const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');

// Compile the vendor SVG path geometry to native vector drawing instructions.
// The menu uses transparent glyphs, with no bitmap, tile, gradient or background.
function compile(name) {
  const svg=fs.readFileSync(path.join(root,'assets/providers',name+'-mark.svg'),'utf8');
  const size=Number(svg.match(/viewBox="0 0 (\d+) (\d+)"/)[1]);
  const shapes=[...svg.matchAll(/<path\s+([^>]+)>/g)];
  const lines=[`        case .${name}:`,'            var paths: [NSBezierPath] = []'];
  for (const shape of shapes) {
    const data=shape[1].match(/\bd="([^"]+)"/)[1];
    const tokens=data.match(/[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?/g);
    let index=0,command='';
    const number=()=>{const value=tokens[index++];if(!Number.isFinite(Number(value)))throw Error('Invalid path number');return value;};
    const point=()=>`NSPoint(x: ${number()}, y: ${number()})`;
    let x='0',y='0';
    lines.push('            do {','                let p = NSBezierPath()');
    if(shape[1].includes('fill-rule="evenodd"'))lines.push('                p.windingRule = .evenOdd');
    while(index<tokens.length) {
      if(/^[A-Za-z]$/.test(tokens[index])) command=tokens[index++];
      switch(command) {
        case 'M': x=number();y=number();lines.push(`                p.move(to: NSPoint(x: ${x}, y: ${y}))`);command='L';break;
        case 'L': x=number();y=number();lines.push(`                p.line(to: NSPoint(x: ${x}, y: ${y}))`);break;
        case 'H': x=number();lines.push(`                p.line(to: NSPoint(x: ${x}, y: ${y}))`);break;
        case 'V': y=number();lines.push(`                p.line(to: NSPoint(x: ${x}, y: ${y}))`);break;
        case 'C': {
          const first=point(),second=point();x=number();y=number();
          lines.push(`                p.curve(to: NSPoint(x: ${x}, y: ${y}), controlPoint1: ${first}, controlPoint2: ${second})`);break;
        }
        case 'Z': lines.push('                p.close()');command='';break;
        default: throw Error('Unsupported SVG command: '+command);
      }
    }
    lines.push('                paths.append(p)','            }');
  }
  lines.push(`            return (paths, ${size})`);
  return lines.join('\n');
}
